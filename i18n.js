function tldrmanBrowserUiLanguage() {
  try {
    if (typeof chrome !== "undefined" && chrome.i18n && typeof chrome.i18n.getUILanguage === "function") {
      return chrome.i18n.getUILanguage();
    }
  } catch (e) { /* ignore */ }
  try {
    if (typeof navigator !== "undefined" && navigator.language) return navigator.language;
  } catch (e) { /* ignore */ }
  return "en";
}

function tldrmanMapBrowserToUi(raw) {
  var s = String(raw || "en").toLowerCase().replace(/_/g, "-");
  var i;
  for (i = 0; i < TLDRMAN_UI_LANG_CODES.length; i++) {
    if (TLDRMAN_UI_LANG_CODES[i].toLowerCase() === s) return TLDRMAN_UI_LANG_CODES[i];
  }
  if (s.indexOf("es-") === 0 || s === "es") {
    var latin = ["es-mx", "es-ar", "es-co", "es-cl", "es-pe", "es-ve", "es-ec", "es-gt", "es-cu", "es-bo", "es-do", "es-hn", "es-py", "es-sv", "es-ni", "es-cr", "es-pa", "es-uy", "es-pr", "es-us", "es-419"];
    if (s === "es-es") return "es-ES";
    if (latin.indexOf(s) !== -1) return "es-419";
    return "es-ES";
  }
  if (s.indexOf("pt-") === 0 || s === "pt") {
    if (s === "pt-br") return "pt-BR";
    if (s === "pt-pt" || s === "pt-ao" || s === "pt-mz") return "pt-PT";
    return "pt-BR";
  }
  if (s === "zh-hk" || s === "zh-mo" || s.indexOf("yue") === 0) return "yue-Hant";
  var base = s.split("-")[0];
  var map = { en: "en", fr: "fr", ar: "ar", de: "de", zh: "zh-CN" };
  if (map[base]) return map[base];
  for (i = 0; i < TLDRMAN_UI_LANG_CODES.length; i++) {
    if (TLDRMAN_UI_LANG_CODES[i].split("-")[0].toLowerCase() === base) return TLDRMAN_UI_LANG_CODES[i];
  }
  return "en";
}

function tldrmanResolveUiLanguage(stored) {
  if (stored && stored !== "browser") {
    for (var i = 0; i < TLDRMAN_UI_LANG_CODES.length; i++) {
      if (TLDRMAN_UI_LANG_CODES[i] === stored) return stored;
    }
  }
  return tldrmanMapBrowserToUi(tldrmanBrowserUiLanguage());
}

function tldrmanT(lang, key, params) {
  var dict = TLDRMAN_UI_STRINGS[lang] || {};
  var en = TLDRMAN_UI_STRINGS.en || {};
  var s = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : en[key];
  if (typeof s !== "string") return key;
  if (params) {
    for (var k in params) {
      if (Object.prototype.hasOwnProperty.call(params, k)) {
        s = s.split("{" + k + "}").join(String(params[k]));
      }
    }
  }
  return s;
}

function tldrmanUiDir(lang) {
  return lang === "ar" ? "rtl" : "ltr";
}

// Applies data-i18n attributes inside root (document by default).
// data-i18n="key" -> textContent, data-i18n-html="key" -> innerHTML,
// data-i18n-title="key" -> title attr, data-i18n-placeholder="key" -> placeholder.
function tldrmanApplyStatic(root, lang) {
  var r = root || (typeof document !== "undefined" ? document : null);
  if (!r || typeof r.querySelectorAll !== "function") return;
  function each(sel, fn) {
    var els = r.querySelectorAll(sel);
    for (var i = 0; i < els.length; i++) fn(els[i]);
  }
  each("[data-i18n]", function (el) { el.textContent = tldrmanT(lang, el.getAttribute("data-i18n")); });
  each("[data-i18n-html]", function (el) { el.innerHTML = tldrmanT(lang, el.getAttribute("data-i18n-html")); });
  each("[data-i18n-title]", function (el) { el.setAttribute("title", tldrmanT(lang, el.getAttribute("data-i18n-title"))); });
  each("[data-i18n-placeholder]", function (el) { el.setAttribute("placeholder", tldrmanT(lang, el.getAttribute("data-i18n-placeholder"))); });
  try {
    var html = (r === document) ? document.documentElement : (r.ownerDocument || document).documentElement;
    html.lang = lang;
    html.dir = tldrmanUiDir(lang);
  } catch (e) { /* ignore */ }
}
